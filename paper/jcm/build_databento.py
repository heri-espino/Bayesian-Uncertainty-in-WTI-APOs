"""Manual Elsevier CAS builder for the independent Databento-only draft.

Stages the authored CAS class/bibliography, and attaches results figures
ONLY IF produced by the complete manual Databento experiment. Preserves
paper/jcm/main.tex and the former Barchart/Wiley/REMEF manuscripts.
"""
from __future__ import annotations

import argparse
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = ROOT / "paper" / "jcm"
CAS = ROOT / "paper" / "els-cas-templates"
BIB = ROOT / "paper" / "manuscript" / "references.bib"
FIGURES = ROOT / "figures" / "aao_databento_only"
BUILD = HERE / "build" / "databento"
STAGE = BUILD / "stage"
PDF = BUILD / "jcm_databento_working_draft.pdf"


def check() -> None:
    necessary = [
        HERE / "databento_main.tex", CAS / "cas-dc.cls",
        CAS / "cas-common.sty", CAS / "cas-model2-names.bst",
        CAS / "thumbnails" / "cas-email.jpeg", BIB,
    ]
    missing = [str(p.relative_to(ROOT)) for p in necessary if not p.is_file()]
    if missing:
        raise ValueError("Missing CAS Databento prerequisites: " + ", ".join(missing))
    source = (HERE / "databento_main.tex").read_text(encoding="utf-8")
    for fragment in (
        r"\documentclass[a4paper,fleqn]{cas-dc}",
        "Databento", "reduced-form", "prior-date",
        r"\bibliography{references}",
        "not yet been run",
    ):
        if fragment not in source:
            raise ValueError(f"Manuscript missing disclosure/section: {fragment}")


def stage() -> None:
    check()
    # Stage is gitignored; it is NEVER a new source data or experiment folder.
    if STAGE.exists():
        shutil.rmtree(STAGE)
    STAGE.mkdir(parents=True)
    for filename in ("cas-dc.cls", "cas-common.sty", "cas-model2-names.bst"):
        shutil.copy2(CAS / filename, STAGE / filename)
    shutil.copytree(CAS / "thumbnails", STAGE / "thumbnails")
    shutil.copy2(BIB, STAGE / "references.bib")
    shutil.copy2(HERE / "databento_main.tex", STAGE / "main.tex")
    if FIGURES.is_dir() and (FIGURES/"figure_manifest.json").is_file():
        folder = STAGE / "figures"
        folder.mkdir()
        for name in (
            "fig06_databento_benchmark_mae.pdf",
            "fig07_databento_date_cluster_intervals.pdf",
            "fig08_databento_mae_time_series.pdf",
        ):
            if not (FIGURES/name).is_file():
                raise ValueError(f"Incomplete numerical figure set: {name}")
            shutil.copy2(FIGURES/name, folder/name)


def build() -> None:
    stage()
    latexmk = shutil.which("latexmk")
    pdflatex = shutil.which("pdflatex")
    bibtex = shutil.which("bibtex")
    if latexmk and pdflatex:
        commands = [[latexmk, "-pdf", "-interaction=nonstopmode",
                     "-halt-on-error", "main.tex"]]
    elif pdflatex and bibtex:
        base = [pdflatex, "-interaction=nonstopmode",
                "-halt-on-error", "main.tex"]
        commands = [base, [bibtex, "main"], base, base]
    else:
        raise SystemExit("Install pdflatex and BibTeX or latexmk")
    for command in commands:
        subprocess.run(command, cwd=STAGE, check=True)
    result = STAGE / "main.pdf"
    if not result.is_file():
        raise RuntimeError("No PDF generated by CAS")
    shutil.copy2(result, PDF)
    print(PDF)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        check()
        print("Databento-only CAS manuscript layout OK (metrics pending)")
    else:
        build()


if __name__ == "__main__":
    main()
